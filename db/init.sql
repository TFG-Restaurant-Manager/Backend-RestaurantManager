-- Ejemplo de llamada a dishes_restaurant: SELECT * FROM dishes_restaurant WHERE restaurant_id = 'id del restaurante buscado'
CREATE VIEW data_restaurant_dishes AS
SELECT 
	d.id,
	d.name,
	c.name as category_name,
	d.description,
	d.price,
	d.available,
	d.restaurant_id
FROM dishes d
JOIN categories c on d.category_id = c.id;

CREATE VIEW restaurant_web_orders AS
SELECT 
	o.id AS order_id,
	o.restaurant_id,
	o.table_id,
	os.name AS status_name,
	o.total,
	o.notes,
	o.created_at,
	oi.dish_id
FROM orders o
JOIN order_status os ON o.status_id = os.id
JOIN order_items oi ON o.id = oi.order_id
WHERE o.order_type_id = 1;-- Pedidos web 'WEB'

CREATE VIEW restaurant_table_orders AS
SELECT 
	o.id AS order_id,
	o.restaurant_id,
	o.table_id,
	os.name AS status_name,
	o.total,
	o.notes,
	o.created_at,
	oi.dish_id
FROM orders o
JOIN order_status os ON o.status_id = os.id
JOIN order_items oi ON o.id = oi.order_id
WHERE o.order_type_id = 2;-- Pedidos en mesa 'TABLE'

