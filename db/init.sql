CREATE OR REPLACE FUNCTION set_employee_code_prefix()
RETURNS TRIGGER AS $$
DECLARE
  prefix_val TEXT; -- Guardará el prefijo del restaurante
BEGIN

	-- Obtener el prefijo del restaurante asociado al nuevo empleado
	SELECT prefix INTO prefix_val
	FROM restaurants
	WHERE id = NEW.restaurant_id; 

	-- Si no se encuentra el restaurante o su prefijo, lanzar un error
	IF prefix_val IS NULL THEN
		RAISE EXCEPTION 'Restaurant prefix not found for id %', NEW.restaurant_id;
	END IF;

	-- Ejemplo: prefix + id con ceros (00001)

  	-- Evita duplicar prefijo si ya viene puesto
	-- Si el codigo no es igual al prefijo seguido de cualquier cosa, entonces lo modifica
	IF NEW.code NOT LIKE prefix_val || '%' THEN
		-- Modifica el valor de code antes de guardarlo en la base de datos
		-- := es asignación en PL/pgSQL (no es comparación)
		NEW.code := prefix_val || NEW.code;
	END IF;

	RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_employee_code_prefix
BEFORE INSERT ON employee
FOR EACH ROW
EXECUTE FUNCTION set_employee_code_prefix();

